// Builds i18n/en.js and i18n/es.js from i18n/keys.json (what the app shows) and i18n/tr.json (the translations).
// Run after tools/i18n-extract.mjs. Reports keys that have no translation yet, and translations with wrong placeholders.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const keys = JSON.parse(readFileSync('i18n/keys.json', 'utf8')).map(x => x.k);
const tr = existsSync('i18n/tr.json') ? JSON.parse(readFileSync('i18n/tr.json', 'utf8')) : {};
// extra translation files passed on the command line are merged into tr.json (later files win)
for (const f of process.argv.slice(2)) Object.assign(tr, JSON.parse(readFileSync(f, 'utf8')));
const missing = [], bad = [];
for (const lang of ['en', 'es']) {
  const out = {};
  for (const k of keys) {
    const v = tr[k] && tr[k][lang];
    if (!v) { if (lang === 'en') missing.push(k); continue; }
    const n = k.split('{}').length - 1, idx = [...v.matchAll(/\{(\d+)\}/g)].map(m => +m[1]);
    if (new Set(idx).size !== n || idx.some(i => i >= n) || v.includes('{}')) { bad.push(lang + ': ' + k); continue; }
    out[k] = v;
  }
  writeFileSync(`i18n/${lang}.js`, '/* generated by tools/i18n-build.mjs – edit i18n/tr.json instead */\nwindow.I18N = ' + JSON.stringify(out) + ';\n');
}
const kept = {}; for (const k of Object.keys(tr).sort()) kept[k] = tr[k];
writeFileSync('i18n/tr.json', JSON.stringify(kept, null, 1));
writeFileSync('i18n/missing.json', JSON.stringify(missing, null, 1));
console.log('keys', keys.length, '| missing', missing.length, '| bad placeholders', bad.length);
if (bad.length) console.log(bad.slice(0, 20).join('\n'));
